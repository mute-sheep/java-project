public class variable {
    public static void main(String[] args){
        //Output and print of variables
        int a = 10;
        System.out.println(a);
        //Variables participate in calculations
        int b = 20,c = 30;
        System.out.println(b + c);
        //Modify the variable value
        int d = 30;
        System.out.println("before modification：" + d);
        d = 40;
        System.out.println("after modification：" + d);
    }
}